const COUNTRY_INDEX: Record<string, Country> = COUNTRIES.reduce<
  Record<string, Country>
>((acc, country) => {
  acc[country.code] = country;
  return acc;
}, {});

export function getCountry(code: string | null | undefined): Country | null {
  if (!code) {
    return null;
  }
  return COUNTRY_INDEX[code.toUpperCase()] ?? null;
}

/**
 * Convert an ISO-2 country code to its flag emoji using Unicode regional
 * indicator symbols. Returns an empty string for invalid codes.
 */
export function flagEmoji(code: string | null | undefined): string {
  if (!code || code.length !== 2) {
    return '';
  }
  const A = 0x1f1e6;
  const upper = code.toUpperCase();
  if (!/^[A-Z]{2}$/.test(upper)) {
    return '';
  }
  return (
    String.fromCodePoint(A + (upper.charCodeAt(0) - 65)) +
    String.fromCodePoint(A + (upper.charCodeAt(1) - 65))
  );
}
